// Заголовок раздела получает фокус: экранный диктор и клавиатура продолжают с выбранного раздела.
function showSection(id: MethodologySection) {
    const heading = document.getElementById(id)
    heading?.scrollIntoView({ block: 'start' })
    heading?.focus({ preventScroll: true })
}

// Короткое пояснение рядом с данными со ссылкой на раздел «О данных».
export function AboutNote({ section, onAbout, children }: { section: MethodologySection, onAbout: OpenAbout, children: ReactNode }) {
    return (
        <p className={styles.note}>
            {children}{' '}
            <button type='button' className={styles.more} onClick={() => onAbout(section)}>Подробнее</button>
        </p>
    )
}

export default function MethodologyPage({ section }: { section?: MethodologySection }) {
    useEffect(() => {
        if (section) {
            showSection(section)
        }
    }, [section])

    return (
        <div className={styles.page}>
            <h1>О данных</h1>
            <nav aria-label='Содержание'>
                <ul className={styles.toc}>
                    {SECTIONS.map(({ id, title }) => (
                        <li key={id}>
                            {/* Раздел — локальное состояние страницы: адрес не меняется. */}
                            <a href={`#${id}`} onClick={event => { event.preventDefault(); showSection(id) }}>{title}</a>
                        </li>
                    ))}
                </ul>
            </nav>
            {SECTIONS.map(({ id, title, content }) => (
                <section key={id}>
                    <h2 id={id} tabIndex={-1}>{title}</h2>
                    {content}
                </section>
            ))}
        </div>
    )
}
